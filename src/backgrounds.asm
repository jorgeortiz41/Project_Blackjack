  LDX PPUSTATUS
  LDX #$3f
  STX PPUADDR
  LDX #$00
  STX PPUADDR
load_palettes:
  LDA palettes,X
  STA PPUDATA
  INX
  CPX #$20
  BNE load_palettes

  ; write sprite data
  LDX #$00
load_sprites:
  LDA sprites,X
  STA $0200,X
  INX
  CPX #$10
  BNE load_sprites

	; write nametables
loadb:
lda PPUSTATUS
lda #$20
sta PPUADDR
lda #$00
sta PPUADDR

ldx #$00
backloop:
lda back, X
sta PPUDATA 
inx 
cpx #$ff
bne backloop

backloop2:
lda back + 256, X
sta PPUDATA 
inx 
cpx #$ff
bne backloop2

backloop3:
lda back + 512, X
sta PPUDATA 
inx 
cpx #$ff
bne backloop3

backloop4:
lda back + 768, X
sta PPUDATA 
inx 
cpx #$c0
bne backloop4

ldx #$a0
loadcard:
	LDA PPUSTATUS
	LDA #$20
	STA PPUADDR
	lda #$65
	STA PPUADDR
	txa
	STA PPUDATA
ldx #$a1
loadcard2:
	LDA PPUSTATUS
	LDA #$20
	STA PPUADDR
	lda #$66
	STA PPUADDR
	txa
	STA PPUDATA



	; finally, attribute table
	; LDA PPUSTATUS
	; LDA #$23
	; STA PPUADDR
	; LDA #$c2
	; STA PPUADDR
	; LDA #%11000000
	; STA PPUDATA

	; LDA PPUSTATUS
	; LDA #$23
	; STA PPUADDR
	; LDA #$e0
	; STA PPUADDR
	; LDA #%00001100
	; STA PPUDATA

vblankwait:       ; wait for another vblank before continuing
  BIT PPUSTATUS
  BPL vblankwait

  LDA #%10010000  ; turn on NMIs, sprites use first pattern table
  STA PPUCTRL
  LDA #%00001110  ; turn on screen
  STA PPUMASK

forever:
  JMP forever
.endproc

